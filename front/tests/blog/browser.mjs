import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('@playwright/test');
const exe = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE;
if (!exe) throw new Error('Set PLAYWRIGHT_CHROMIUM_EXECUTABLE to a Chromium executable');
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--single-process', '--no-zygote'] });
try {
  await fetch('http://localhost:43101/__test/reset');
  const context = await browser.newContext();
  await context.addCookies([{ name: 'access_token', value: 'test', domain: 'localhost', path: '/' }]);
  const page = await context.newPage();
  const failures = []; page.on('pageerror', error => failures.push(error.message));
  await page.goto('http://localhost:43100/admin/blog/new', { waitUntil: 'networkidle' });
  await page.getByLabel('عنوان *').fill('مقاله آزمایشی');
  await page.getByLabel('نامک *').fill('test-blog');
  await page.getByLabel('خلاصه', { exact: true }).fill('خلاصه آزمایشی');
  await page.locator('form select').first().selectOption('published');
  const editor = page.locator('.ProseMirror'); await editor.waitFor();
  await editor.click(); await page.keyboard.type('Intro'); await page.keyboard.press('Enter');
  await page.keyboard.type('/');
  await page.getByRole('button', { name: 'تیتر 2', exact: true }).first().waitFor();
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); await page.keyboard.type('Section'); await page.keyboard.press('Enter');
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'سوالات متداول' });
  await page.getByRole('button', { name: 'افزودن سوال' }).click();
  await page.getByPlaceholder('سوال', { exact: true }).fill('سوال آزمایشی');
  await page.getByPlaceholder('پاسخ', { exact: true }).fill('پاسخ آزمایشی');
  let faq = page.locator('[data-node-view-wrapper]').filter({ has: page.getByPlaceholder('سوال', { exact: true }) });
  await faq.getByRole('button', { name: 'انتقال بالا', exact: true }).first().click();
  faq = page.locator('[data-node-view-wrapper]').filter({ has: page.getByPlaceholder('سوال', { exact: true }) });
  await faq.getByRole('button', { name: 'انتقال پایین', exact: true }).first().click();
  await faq.getByRole('button', { name: 'کپی بلوک', exact: true }).click();
  assert.equal(await page.getByPlaceholder('سوال', { exact: true }).count(), 2);
  await page.locator('[data-node-view-wrapper]').filter({ has: page.getByPlaceholder('سوال', { exact: true }) }).last().getByRole('button', { name: 'حذف بلوک', exact: true }).click();
  assert.equal(await page.getByPlaceholder('سوال', { exact: true }).count(), 1);
  // Add a table of contents and a live barber slider after the FAQ.
  await editor.locator(':scope > p').last().click();
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'فهرست مطالب' });
  await editor.locator(':scope > p').last().click();
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'اسلایدر آرایشگرها' });
  await page.getByPlaceholder('نام آرایشگاه').fill('سالن');
  await page.getByRole('button', { name: 'جستجو', exact: true }).click();
  await page.getByRole('button', { name: 'سالن آزمایشی +' }).click();
  await editor.locator(':scope > p').last().click();
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'تصویر' });
  await page.getByLabel('آدرس رسانه').fill('/logo/icon-192.png');
  await page.getByLabel('متن جایگزین').fill('تصویر آزمایشی');
  await editor.locator(':scope > p').last().click();
  await page.getByRole('button', { name: 'پیوند', exact: true }).first().click();
  await page.getByLabel('آدرس', { exact: true }).fill('/pricing');
  await page.getByLabel('متن پیوند', { exact: true }).fill('تعرفه‌ها');
  await page.getByRole('button', { name: 'اعمال', exact: true }).click();
  await editor.locator(':scope > p').last().click();
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'ویدیو' });
  await page.getByLabel('آدرس رسانه').last().fill('/uploads/blog/demo.mp4');
  await page.getByLabel('آدرس پوستر').fill('/logo/icon-192.png');
  await page.getByLabel('بی‌صدا').check();
  await page.getByLabel('پخش خودکار').last().check();
  await editor.locator(':scope > p').last().click();
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'گالری' });
  await page.getByRole('button', { name: 'افزودن رسانه' }).click();
  await page.getByLabel('آدرس رسانه').last().fill('/logo/icon-192.png');
  await page.getByLabel('متن جایگزین').last().fill('تصویر گالری');
  await editor.locator(':scope > p').last().click();
  await page.getByRole('combobox', { name: 'درج بلوک' }).selectOption({ label: 'جدول' });
  await page.getByRole('button', { name: 'تمام‌صفحه' }).click();
  assert.equal(await page.locator('.blog-editor-fullscreen').count(), 1);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.blog-editor-fullscreen').count(), 0);
  // HTML view round-trips custom node attributes and must not apply on cancel.
  await page.getByRole('button', { name: 'HTML', exact: true }).click();
  await page.getByRole('button', { name: 'اعمال', exact: true }).click();
  assert.equal(await page.getByPlaceholder('سوال', { exact: true }).inputValue(), 'سوال آزمایشی');
  await page.getByRole('button', { name: 'ذخیره مقاله' }).click();
  await page.waitForURL('**/admin/blog/1', { timeout: 15000 });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByPlaceholder('سوال', { exact: true }).inputValue(), 'سوال آزمایشی');
  const publicPage = await context.newPage(); await publicPage.goto('http://localhost:43100/blog/test-blog', { waitUntil: 'networkidle' });
  await publicPage.getByRole('heading', { name: 'مقاله آزمایشی' }).waitFor();
  assert.equal(await publicPage.getByText('سوال آزمایشی').count(), 1);
  assert.equal(await publicPage.locator('h2#section-section').count(), 1);
  assert.equal(await publicPage.getByRole('link', { name: 'سالن آزمایشی مشاهده صفحه آرایشگر' }).count(), 1);
  assert.equal(await publicPage.getByRole('img', { name: 'تصویر آزمایشی' }).count(), 1);
  assert.equal(await publicPage.locator('article a[href="/pricing"]').count(), 1);
  assert.equal(await publicPage.getByRole('navigation', { name: 'فهرست مطالب' }).count(), 1);
  assert.equal(await publicPage.locator('video[poster="/logo/icon-192.png"]').count(), 1);
  assert.equal(await publicPage.getByRole('img', { name: 'تصویر گالری' }).count(), 1);
  assert.equal(await publicPage.locator('article table').count(), 1);
  await fetch('http://localhost:43101/__test/hide-barber');
  await publicPage.reload({ waitUntil: 'networkidle' });
  assert.equal(await publicPage.getByRole('link', { name: 'سالن آزمایشی مشاهده صفحه آرایشگر' }).count(), 0);

  const mobile = await context.newPage();
  await mobile.setViewportSize({ width: 390, height: 844 });
  await mobile.goto('http://localhost:43100/admin/blog/1', { waitUntil: 'networkidle' });
  await mobile.locator('.ProseMirror').waitFor();
  assert.equal(await mobile.locator('html').getAttribute('dir'), 'rtl');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true, 'mobile page must not overflow horizontally');
  await mobile.getByRole('button', { name: 'تمام‌صفحه' }).click();
  assert.equal(await mobile.locator('.blog-editor-fullscreen').count(), 1);
  await mobile.keyboard.press('Escape');
  assert.equal(await mobile.locator('.blog-editor-fullscreen').count(), 0);
  assert.deepEqual(failures, []);
  console.log('PASS: browser editor → save → reload → public rendering (mock API)');
} finally { await browser.close(); }
