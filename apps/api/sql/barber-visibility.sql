-- تفکیک نمایش عمومی آرایشگر از وضعیت ورود حساب
-- در production هنگام راه‌اندازی بک‌اند در صورت وجود دسترسی ALTER به‌طور خودکار
-- ساخته می‌شود. اگر دسترسی وجود ندارد، پس از بررسی نبود ستون، این دستور را اجرا کنید.
-- این دستور هیچ حسابی را فعال یا غیرفعال نمی‌کند؛ حساب‌های قدیمی که isActive=0
-- دارند باید جداگانه در مدیریت آرایشگرها بررسی و در صورت نیاز باز شوند.
ALTER TABLE `barber_profile`
  ADD COLUMN `is_publicly_visible` TINYINT(1) NOT NULL DEFAULT 1;
